//! JUnit 5 test synthesis from verification findings.

use crate::report::{Finding, Severity};

/// Generate a JUnit 5 test class from verification findings.
pub fn generate_junit5(findings: &[Finding], class_name: &str) -> String {
    let mut out = String::new();
    out.push_str("// Auto-generated by Keller-VIR Java Bytecode Verifier\n");
    out.push_str("// Do not edit manually.\n\n");
    out.push_str("import org.junit.jupiter.api.Test;\n");
    out.push_str("import static org.junit.jupiter.api.Assertions.*;\n\n");

    let test_class = to_test_class_name(class_name);
    out.push_str(&format!("public class {} {{\n\n", test_class));

    for finding in findings {
        if finding.severity == Severity::Error || finding.severity == Severity::Warning {
            out.push_str(&generate_test_method(finding, &test_class));
        }
    }

    out.push_str("}\n");
    out
}

/// Generate a single @Test method for a finding.
fn generate_test_method(finding: &Finding, test_class: &str) -> String {
    let mut out = String::new();
    let method_name = to_snake_case(&finding.id);

    out.push_str("    @Test\n");
    out.push_str(&format!("    void {}() {{\n", method_name));
    out.push_str("        // Invariant: ");
    out.push_str(&finding.invariant);
    out.push('\n');
    out.push_str("        // Expected: no exception thrown\n");
    out.push_str("        assertDoesNotThrow(() -> {\n");
    out.push_str("            // TODO: instantiate and invoke the method under test\n");
    out.push_str("            // Object obj = new ");
    out.push_str(test_class);
    out.push_str("();\n");
    out.push_str("        });\n");
    out.push_str("    }\n\n");

    out
}

/// Convert a class name like "com.example.Foo" to "FooTest".
fn to_test_class_name(class_name: &str) -> String {
    let simple = class_name.rsplit('.').next().unwrap_or(class_name);
    format!("{}Test", simple)
}

/// Convert an ID like "NPE-com.example.Foo-bar" to snake_case method name.
fn to_snake_case(id: &str) -> String {
    id.chars()
        .enumerate()
        .map(|(i, c)| {
            if i == 0 {
                c.to_ascii_lowercase()
            } else if c == '-' || c == '.' || c == '/' {
                '_'
            } else if c.is_uppercase() {
                c.to_ascii_lowercase()
            } else {
                c
            }
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_generate_junit5_empty() {
        let src = generate_junit5(&[], "com.example.Foo");
        assert!(src.contains("public class FooTest"));
        assert!(!src.contains("void test_"));
    }

    #[test]
    fn test_generate_junit5_with_finding() {
        let findings = vec![Finding {
            id: "NPE-com.example.Foo-bar".into(),
            severity: Severity::Warning,
            file: "Foo.class".into(),
            line: 10,
            message: "null deref".into(),
            invariant: "obj != null".into(),
        }];
        let src = generate_junit5(&findings, "com.example.Foo");
        assert!(src.contains("public class FooTest"));
        assert!(src.contains("@Test"));
        assert!(src.contains("npe_com_example_foo_bar"));
    }

    #[test]
    fn test_to_test_class_name() {
        assert_eq!(to_test_class_name("com.example.Foo"), "FooTest");
        assert_eq!(to_test_class_name("Bar"), "BarTest");
    }
}
