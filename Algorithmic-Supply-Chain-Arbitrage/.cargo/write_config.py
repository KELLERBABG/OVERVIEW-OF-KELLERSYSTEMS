from pathlib import Path
import subprocess, textwrap, sys

sysroot = subprocess.check_output(["rustc", "--print-sysroot"]).decode().strip()
lld = Path(sysroot) / "lib/rustlib/x86_64-pc-windows-msvc/bin/gcc-ld/lld-link.exe"
lld_win = lld.as_posix().replace("/", "\\")

config = textwrap.dedent(f"""\
    # Workspace-level build configuration for ASCA on Windows.
    #
    # The workspace pins the stable MSVC toolchain in rust-toolchain.toml so the
    # same toolchain is used locally and in CI. On this host the default PATH
    # resolves the linker command `link.exe` to GNU coreutils /usr/bin/link.exe
    # (a symlink creator), which is why rustc's MSVC link step fails with
    # "link: extra operand …" locally. Point the MSVC target's host linker at the
    # rustc-shipped LLD-based link.exe so that a clean checkout from the repo root
    # can build and test without any CARGO_TARGET_DIR workaround.
    #
    # This file is generated by .cargo/write_config.py; run it again if the
    # rustup sysroot moves.

    [target.x86_64-pc-windows-msvc]
    linker = "{lld_win}"
    """).strip() + "\n"

out = Path(".cargo/config.toml")
out.write_text(config)
print("wrote", out)
print(config)
