/**
 * Downloads the self-hosted application fonts.
 *
 *   node scripts/setup-fonts.mjs
 *
 * Produces assets/fonts/*.woff2 and assets/fonts/fonts.css. Run it once after a
 * clone; the files are committed, so a normal build does not need the network.
 *
 * Injection is deliberately NOT done here. Two other scripts read fonts.css and
 * inline it:
 *   - scripts/build-site.mjs and scripts/build-docs.mjs, for every page they
 *     generate,
 *   - the top-level pages are patched in place and carry the rules already.
 * Patching generated output here as well is what broke silently before: a build
 * ran afterwards and restored the Google Fonts tags. This script only produces
 * assets; scripts/check-offline.mjs asserts the result.
 *
 * Why self-host at all: the desktop build must render identically with no
 * network, and the old Google Fonts request sent every visitor's IP to a font
 * CDN, which the Datenschutzerklaerung had to disclose.
 *
 * Only the `latin` and `latin-ext` subsets are fetched: between them they carry
 * the German umlauts (U+00C4-U+00FC), the sharp s, the section sign, the euro
 * sign and the German quotation marks. Cyrillic, Greek and Vietnamese are
 * dropped rather than shipped for nothing.
 *
 * IBM Plex is licensed under the SIL Open Font License 1.1, which permits
 * redistribution. The OFL notice is written alongside the files.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";

const SUBSETS = ["latin", "latin-ext"];
const FONT_DIR = "assets/fonts";
const CSS_OUT = `${FONT_DIR}/fonts.css`;

const FAMILIES = [
  { name: "IBM Plex Sans", css: "IBM+Plex+Sans:wght@300;400;500;600;700", slug: "plex-sans" },
  { name: "IBM Plex Mono", css: "IBM+Plex+Mono:wght@400;500;600", slug: "plex-mono" },
];

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36";

const GOOGLE_URL =
  "https://fonts.googleapis.com/css2?family=" +
  FAMILIES.map((f) => f.css).join("&family=") +
  "&display=swap";

function fail(msg) {
  console.error(`FAILED: ${msg}`);
  process.exit(1);
}

/* --------------------------------------------------------------------------
 * 1. Fetch the CSS, keep only the subsets we ship
 * ------------------------------------------------------------------------ */

mkdirSync(FONT_DIR, { recursive: true });

let css;
try {
  css = execFileSync("curl", ["-sS", "--max-time", "90", "-A", UA, GOOGLE_URL], {
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
  });
} catch (error) {
  fail(`could not reach Google Fonts: ${error.message}`);
}

if (!css.includes("@font-face")) fail("the response contains no @font-face rules");

/* Each rule is preceded by a `/* subset *\/` comment. */
const blocks = [];
const ruleRe = /\/\*\s*([a-z0-9-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g;
let m;
while ((m = ruleRe.exec(css))) {
  if (!SUBSETS.includes(m[1])) continue;
  blocks.push({ subset: m[1], rule: m[2] });
}

if (!blocks.length) fail("no @font-face rules matched the wanted subsets");

/* --------------------------------------------------------------------------
 * 2. Download each file and rewrite the url() to a local path
 * ------------------------------------------------------------------------ */

const downloaded = [];
const localRules = [];

for (const block of blocks) {
  const family = /font-family:\s*'([^']+)'/.exec(block.rule);
  const weight = /font-weight:\s*(\d+)/.exec(block.rule);
  const style = /font-style:\s*(\w+)/.exec(block.rule);
  const url = /url\((https:\/\/[^)]+\.woff2)\)/.exec(block.rule);
  if (!family || !weight || !url) fail(`incomplete @font-face rule for ${block.subset}`);

  const slug = FAMILIES.find((f) => f.name === family[1])?.slug;
  if (!slug) fail(`unexpected family "${family[1]}"`);

  const file = `${slug}-${weight[1]}-${style ? style[1] : "normal"}-${block.subset}.woff2`;
  const target = `${FONT_DIR}/${file}`;

  if (!existsSync(target)) {
    execFileSync("curl", ["-sSL", "--max-time", "120", "-A", UA, "-o", target, url[1]], {
      stdio: ["ignore", "ignore", "inherit"],
    });
  }

  const size = readFileSync(target).length;
  /* A woff2 file is smaller than this only if it is an error page. */
  if (size < 1024) fail(`${target} is only ${size} bytes; download looks broken`);

  downloaded.push({ file, size, subset: block.subset });
  localRules.push(
    block.rule
      .replace(/url\(https:\/\/[^)]+\.woff2\)/, `url("./${file}")`)
      /* The generator's own subset markers are irrelevant once inlined. */
      .replace(/\/\*\s*[a-z0-9-]+\s*\*\//, "")
  );
}

const header = `/*
 * IBM Plex Sans / IBM Plex Mono - self-hosted subsets (${SUBSETS.join(", ")}).
 *
 * Generated by scripts/setup-fonts.mjs. Do not edit by hand.
 * (c) IBM Corp., licensed under the SIL Open Font License 1.1 - see OFL.txt.
 *
 * Self-hosted so the pages and the desktop build render identically with no
 * network request, and so no visitor IP is sent to a font CDN.
 */
`;

writeFileSync(CSS_OUT, header + localRules.join("\n") + "\n", "utf8");

/* --------------------------------------------------------------------------
 * 3. Ship the licence notice with the files
 * ------------------------------------------------------------------------ */

writeFileSync(
  `${FONT_DIR}/OFL.txt`,
  `IBM Plex is licensed under the SIL Open Font License, Version 1.1.

Copyright (c) 2017 IBM Corp. All rights reserved.

This Font Software is licensed under the SIL Open Font License, Version 1.1.
This license is available with a FAQ at: https://scripts.sil.org/OFL

The full license text is at:
https://github.com/IBM/plex/blob/master/LICENSE.txt

Redistribution of the font files in this directory is permitted by that
license. The files here are the Google Fonts "latin" and "latin-ext" subsets of
IBM Plex Sans and IBM Plex Mono, served as woff2.
`,
  "utf8"
);

/* --------------------------------------------------------------------------
 * 4. Report
 * ------------------------------------------------------------------------ */

const bytes = downloaded.reduce((n, d) => n + d.size, 0);
console.log(`self-hosted fonts -> ${FONT_DIR}`);
console.log(`  files      : ${downloaded.length} (${SUBSETS.join(", ")})`);
console.log(`  total size : ${(bytes / 1024).toFixed(0)} KiB`);
console.log(`  css        : ${CSS_OUT}`);
console.log("\nnext: node scripts/check-offline.mjs   # assert every page is self-contained");
