/**
 * Verifies the pages are self-contained.
 *
 *   node scripts/check-offline.mjs
 *
 * This is deliberately mechanical rather than browser-driven. A headless Chrome
 * launch costs 40-200s in this environment, which makes a per-page render check
 * unusable; the properties that actually matter are all statically checkable:
 *
 *   1. every url() in the @font-face rules resolves to a real woff2 file,
 *   2. those files are valid woff2, not error pages saved under a .woff2 name,
 *   3. the subsets present cover the characters the German UI needs,
 *   4. each page carries the inlined rules, so it needs no stylesheet request,
 *   5. no page references a font CDN or any other external host.
 *
 * The rendered result is confirmed separately by screenshots; what this guards
 * is the regression that matters, namely a font quietly going missing again.
 */
import { readFileSync, existsSync, statSync, readdirSync } from "node:fs";
import { join } from "node:path";

const PAGES = (() => {
  /* Every page in the repository, not just the three hand-maintained ones: the
     legal, pricing and checkout pages are generated by scripts/build-site.mjs,
     and a stale template there once reintroduced the Google Fonts links. */
  const found = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.name === "node_modules" || entry.name === ".git" || entry.name === "dist" || entry.name === "src-tauri") continue;
      const path = join(dir, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (entry.name.endsWith(".html")) found.push(path);
    }
  };
  walk(".");
  return found.sort();
})();
const FONT_DIR = "assets/fonts";
const CSS = join(FONT_DIR, "fonts.css");

let failures = 0;
const problem = (msg) => { console.log(`  FAIL  ${msg}`); failures++; };

function ok(msg) { console.log(`  ok    ${msg}`); }

/* --------------------------------------------------------------------------
 * 1. The stylesheet and every file it names
 * ------------------------------------------------------------------------ */

console.log("font assets\n");

if (!existsSync(CSS)) {
  problem(`${CSS} is missing; run: node scripts/setup-fonts.mjs`);
  process.exit(1);
}

const css = readFileSync(CSS, "utf8");
const urls = [...css.matchAll(/url\("\.\/([^"]+\.woff2)"\)/g)].map((m) => m[1]);
const faces = [...css.matchAll(/@font-face\s*\{[^}]*\}/g)].map((m) => m[0]);

if (!faces.length) problem("fonts.css declares no @font-face rules");
if (new Set(urls).size !== urls.length) problem("fonts.css references the same file twice");

for (const url of new Set(urls)) {
  const path = join(FONT_DIR, url);
  if (!existsSync(path)) { problem(`referenced file is missing: ${path}`); continue; }
  const buf = readFileSync(path);
  const magic = buf.subarray(0, 4).toString("latin1");
  if (magic !== "wOF2") problem(`${url} is not a woff2 file (magic "${magic}")`);
  if (buf.length < 1024) problem(`${url} is implausibly small (${buf.length} bytes)`);
}

ok(`${faces.length} @font-face rules, ${new Set(urls).size} files, all valid woff2`);

/* 8 faces per subset: 5 sans weights + 3 mono weights. */
const subsets = ["latin", "latin-ext"];
for (const subset of subsets) {
  const count = urls.filter((u) => u.endsWith(`-${subset}.woff2`)).length;
  if (count !== 8) problem(`expected 8 files for the ${subset} subset, found ${count}`);
}
ok("both subsets present with all 8 weights");

/* --------------------------------------------------------------------------
 * 2. Character coverage the UI depends on
 *
 * Coverage is a property of the two subsets together, not of either one alone:
 * the German umlauts (U+00C4-U+00FC), the section sign (U+00A7) and the euro
 * sign (U+20AC) all sit in the *latin* range U+0000-00FF, while latin-ext only
 * picks up from U+0100. Asserting per subset produces false alarms, so the
 * ranges are unioned.
 * ------------------------------------------------------------------------ */

const allRanges = faces
  .map((f) => (/unicode-range:\s*([^;]+);/.exec(f) || [])[1] || "")
  .join(",");

function covered(cp, ranges) {
  const hex = cp.toString(16).toUpperCase();
  return ranges.split(",").some((part) => {
    const spec = part.trim().replace(/^U\+/i, "");
    if (!spec) return false;
    if (spec.includes("?")) {
      const re = new RegExp("^" + spec.replace(/\?/g, "[0-9A-F]") + "$", "i");
      return re.test(hex.padStart(spec.length, "0"));
    }
    const [lo, hi] = spec.split("-");
    const low = parseInt(lo, 16);
    const high = hi ? parseInt(hi, 16) : low;
    return cp >= low && cp <= high;
  });
}

const UI_SAMPLE = [
  "BauLens Prüfbericht", "Grundstücksfläche", "Gebäudehöhe", "Straße",
  "Abstandsflächen", "Vollgeschosse", "Rettungswege", "Gründach",
  "Barrierefreiheit", "Schallschutz", "Bebauungsplan", "Änderungsverlauf",
  "§2 MBO", "§19 BauNVO", "149 €", "1.499 $", "38°–45°", "„Muster“",
];

const uncovered = new Map();
for (const text of UI_SAMPLE) {
  for (const ch of text) {
    const cp = ch.codePointAt(0);
    if (cp < 0x20) continue;
    if (!covered(cp, allRanges)) uncovered.set(ch, cp.toString(16).toUpperCase());
  }
}

if (uncovered.size) {
  problem(
    "the shipped ranges do not cover: " +
    [...uncovered].map(([c, h]) => `${JSON.stringify(c)} (U+${h})`).join(", ")
  );
} else {
  ok(`the two subsets together cover all ${UI_SAMPLE.length} UI samples`);
  ok("umlauts, sharp s, section sign, euro, en/em dash and German quotes included");
}

/* --------------------------------------------------------------------------
 * 3. Every page carries the rules inline and names no external host
 * ------------------------------------------------------------------------ */

console.log("\npages\n");

/* Only sub-resources are fetched at load time. An <a href> to GitHub or the
   Polar checkout is a deliberate navigation target, not an offline dependency,
   so the two are reported separately rather than lumped together. */
const RESOURCE_ATTR = /\b(?:src)\s*=\s*["']https?:\/\/([^"'/]+)|\brel\s*=\s*["']stylesheet["'][^>]*href\s*=\s*["']https?:\/\/([^"'/]+)|\bhref\s*=\s*["']https?:\/\/([^"'/]+)["'][^>]*\brel\s*=\s*["']stylesheet["']/g;
const ANCHOR_ATTR = /<a\b[^>]*\bhref\s*=\s*["']https?:\/\/([^"'/]+)/g;

for (const page of PAGES) {
  if (!existsSync(page)) { problem(`${page} is missing`); continue; }
  const html = readFileSync(page, "utf8");
  const before = failures;

  const inlineFaces = (html.match(/@font-face\s*\{[^}]*\}/g) || []).length;
  if (inlineFaces !== faces.length) {
    problem(`${page} inlines ${inlineFaces} @font-face rules, expected ${faces.length} - run scripts/setup-fonts.mjs`);
  }

  if (/fonts\.(googleapis|gstatic)\.com/.test(html)) {
    problem(`${page} still names a Google Fonts host`);
  }

  const resources = [...html.matchAll(RESOURCE_ATTR)]
    .map((m) => m[1] || m[2] || m[3])
    .filter(Boolean);
  const externalResources = [...new Set(resources)].filter((h) => !h.startsWith("127.0.0.1"));
  if (externalResources.length) {
    problem(`${page} loads external resource(s): ${externalResources.join(", ")}`);
  }

  const links = [...new Set([...html.matchAll(ANCHOR_ATTR)].map((m) => m[1]))]
    .filter((h) => !h.startsWith("127.0.0.1"));

  if (failures === before) {
    const suffix = links.length ? `, ${links.length} external hyperlink(s): ${links.join(", ")}` : "";
    ok(`${page.padEnd(14)} ${inlineFaces} inlined faces, no external resources${suffix}`);
  }
}

/* --------------------------------------------------------------------------
 * 4. Licence notice travels with the files
 * ------------------------------------------------------------------------ */

if (!existsSync(join(FONT_DIR, "OFL.txt"))) {
  problem("assets/fonts/OFL.txt is missing; the OFL requires the notice to ship with the files");
} else {
  ok("OFL.txt present for the bundled fonts");
}

const total = urls.reduce((n, u) => n + (existsSync(join(FONT_DIR, u)) ? statSync(join(FONT_DIR, u)).size : 0), 0);
console.log(`\ntotal font payload: ${(total / 1024).toFixed(0)} KiB`);
console.log(failures === 0 ? "OFFLINE VERIFIED: every page is self-contained" : `\n${failures} problem(s)`);
process.exit(failures === 0 ? 0 : 1);
